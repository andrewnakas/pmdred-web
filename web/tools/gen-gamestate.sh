#!/usr/bin/env bash
# Emits web/test/gamestate.json: the addresses and struct offsets the "did it
# actually reach dungeon play" gate reads out of the running game.
#
#   ./gen-gamestate.sh <path-to-pmd-red-checkout>
#
# Both halves come from the build, not from a wiki or a hand-typed table:
#   * addresses   <- pmd_red.sym, produced by `make syms` on the matching build
#   * offsets     <- offsets.sh, which compiles the decomp's headers with agbcc
#
# Regenerate this whenever the pinned upstream revision moves. EWRAM addresses
# and struct layout both shift with the source.
set -euo pipefail
REPO="$(cd "${1:?usage: gen-gamestate.sh <pmd-red checkout>}" && pwd)"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# The checkout is normally left tidied to save disk, so fall back to the copy
# kept beside it. Either way the symbols come from the matching build.
SYM="${SYM:-$REPO/pmd_red.sym}"
[ -f "$SYM" ] || SYM="$HERE/../../build-artifacts/pmd_red.sym"
[ -f "$SYM" ] || { echo "no pmd_red.sym -- run 'make syms' in $REPO" >&2; exit 1; }

OFFSETS="$("$HERE/offsets.sh" "$REPO")"

REV="$(git -C "$REPO" rev-parse HEAD)"
# The built ROM is deleted after verification rather than kept around as a
# second copy of the user's cartridge; red.sha1 is upstream's record of it and
# the build refuses to finish unless it matches.
ROMSHA="$(awk '{print $1}' "$REPO/red.sha1")"

python3 - "$SYM" "$REV" "$ROMSHA" "$HERE/../test/gamestate.json" <<PY
import json, sys
sym, rev, romsha, out = sys.argv[1:5]
# EWRAM pointers/counters that say which part of the game is running.
WANT = {
    'gDungeon': 'Dungeon* -- NULL except while a dungeon run is executing (src/run_dungeon.c)',
    'sPersonalityTestTracker': 'non-NULL only while the opening personality quiz is running',
    'gDungeonFramesCounter': 'ticks once per rendered dungeon frame',
    'gDungeonBrightness': 'dungeon fade level',
    'gDungeonMenu': 'MenuInputStruct for the dungeon menus; .menuIndex is the cursor row',
    'gDungeonSubMenuItemsCount': 'number of rows in the dungeon submenu currently open',
}
addrs = {}
for line in open(sym):
    p = line.split()
    if len(p) != 4:
        continue
    a, _bind, _size, name = p
    if name in WANT and name not in addrs:
        addrs[name] = int(a, 16)
missing = [k for k in WANT if k not in addrs]
if missing:
    sys.exit('symbols not found in %s: %s' % (sym, ', '.join(missing)))
doc = {
    'upstreamRevision': rev,
    'builtRomSha1': romsha,
    'note': 'generated by web/tools/gen-gamestate.sh -- do not hand-edit',
    'symbolNotes': WANT,
    'symbols': addrs,
    'offsets': json.loads('''$OFFSETS'''),
    'constants': {
        'ENTITY_MONSTER': 1,
        # src/dungeon_main.c, enum above ShowMainMenu()
        'MAIN_MENU_MOVES': 0, 'MAIN_MENU_ITEMS': 1, 'MAIN_MENU_TEAM': 2,
        'MAIN_MENU_OTHERS': 3, 'MAIN_MENU_GROUND': 4,
        # src/dungeon_menu_others.c
        'OTHERS_GAME_OPTIONS': 0, 'OTHERS_QUICKSAVE_GIVEUP': 1, 'OTHERS_MESSAGE_LOG': 2,
        'DUNGEON_TINY_WOODS': 0,
        'DUNGEON_MAX_SIZE_X': 56,
        'DUNGEON_MAX_SIZE_Y': 32,
        'EWRAM_BASE': 0x02000000,
    },
}
open(out, 'w').write(json.dumps(doc, indent=2) + '\n')
print('wrote ' + out)
PY
